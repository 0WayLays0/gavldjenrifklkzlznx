/** Sandstone Pillar: a pillar of sandstone bursts up out of the ground under the foe aimed at, hurling it into the air. */
@AutoSpellConfig
public class SandstonePillarSpell extends SandSpell {
    public static final double RANGE = 20;
    public static final float HEIGHT = 4;

    public SandstonePillarSpell() {
        super("sandstone_pillar", SpellRarity.UNCOMMON, 8, 8, CastType.INSTANT, SpellAnimations.TOUCH_GROUND_ANIMATION);
        this.manaCostPerLevel = 4;
        this.baseSpellPower = 6;
        this.spellPowerPerLevel = 1;
        this.castTime = 0;
        this.baseManaCost = 30;
    }

    @Override
    public List<MutableComponent> getUniqueInfo(int spellLevel, LivingEntity caster) {
        return List.of(
                Component.translatable("ui.irons_spellbooks.damage", Utils.stringTruncation(getPower(spellLevel, caster), 1)),
                Component.translatable("ui.irons_spellbooks.cast_range", Utils.stringTruncation(RANGE, 1)));
    }

    @Override
    public void onCast(Level level, int spellLevel, LivingEntity entity, CastSource castSource, MagicData playerMagicData) {
        if (level instanceof ServerLevel server) {
            Vec3 at = aimedSpot(level, entity, RANGE);
            SandScene.spawn(server, entity, this, SandScene.Kind.PILLAR, at, new Vector3f(0, 1, 0), HEIGHT, 60, getPower(spellLevel, entity));
        }
        super.onCast(level, spellLevel, entity, castSource, playerMagicData);
    }
}
